#!/usr/bin/env python3
"""Lift the two About components onto the homepage, so the hover shows the
real thing rather than a picture of it.

    python3 tools/build-home-about.py

The skill cloud and the experience timeline are taken from about/index.html
as they stand and written into assets/home-v2-about.js. Their styles are not
scoped to the About page, and the homepage already loads the same stylesheet,
so they arrive looking like themselves. The card shrinks them with a
transform, which leaves them live: the pills still answer the cursor.

Run it again whenever the About page changes.
"""
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "about/index.html"
OUT = ROOT / "assets/home-v2-about.js"

WANT = {"skills": "about-skill-cloud", "work": "about-experience-timeline"}


def block(src, cls):
    i = src.index('<div class="%s"' % cls)
    depth = 0
    for m in re.finditer(r"<(/?)div\b", src[i:]):
        depth += -1 if m.group(1) else 1
        if depth == 0:
            return src[i:src.index(">", i + m.end()) + 1]
    sys.exit("unbalanced <div> around " + cls)


def main():
    src = SRC.read_text()
    out = {}
    for key, cls in WANT.items():
        if src.count('<div class="%s"' % cls) != 1:
            sys.exit("not in about/index.html exactly once: " + cls)
        html = block(src, cls)
        # the About page writes these relative to itself
        html = html.replace('src="/assets/', 'src="/assets/')
        out[key] = re.sub(r"\n\s+", " ", html).strip()
        print("  %-28s %5d chars" % (cls, len(out[key])))

    # The Experience card shows only the places: the timeline's own logo
    # tiles, each one once, in the order the timeline lists them.
    seen, logos = set(), []
    for tile in re.findall(r'<div class="about-experience-logo[^"]*"[^>]*>.*?</div>',
                           out["work"]):
        src = re.search(r'src="([^"]+)"', tile).group(1)
        if src not in seen:
            seen.add(src)
            logos.append(tile)
    out["work_logos"] = logos
    print("  %-28s %5d tiles" % ("experience logos", len(logos)))

    OUT.write_text(
        "// Generated by tools/build-home-about.py from about/index.html.\n"
        "// The real components, so the hover card can show the real thing.\n"
        "window.HV2_ABOUT = %s;\n" % json.dumps(out, indent=2))
    print("%s written" % OUT.relative_to(ROOT))


if __name__ == "__main__":
    main()
